/* gen_desktop.h - our own desktop (holyc/desktop: dwl fork + dmenu + lemonbar). stb-style single header.
 *
 * Format source: desktop/src/theme.c (COLOR(0xrrggbbaa) macro, rootcolor/bordercolor/focuscolor/urgentcolor, borderpx, fullscreen_bg),
 * desktop/src/menu.c (colors[SchemeLast][2] fg,bg pairs, rofi_bg) and desktop/src/bar.c (S_FOC/S_DIM/S_ACC lemonbar format strings).
 * The desktop is compiled in (dwm style), so this is a fragment to paste/include and rebuild; colorado never edits the desktop sources.
 * The theme.c part is real C and is compile-checked against the COLOR macro in the tests.
 */
#ifndef COLORADO_GEN_DESKTOP_H
#define COLORADO_GEN_DESKTOP_H
#include "gen.h"

static const char *co_c32(co_rgb c) { static char r[16][16]; static int i; i = (i + 1) & 15; snprintf(r[i], 16, "0x%02x%02x%02xff", c.r, c.g, c.b); return r[i]; }

static void co_gen_desktop(const co_theme *t, co_set *s) {
	const co_rgb *c = t->c; co_sb *o = &co_set_add(s, "desktop", W_CONFIG, "colorado/desktop-theme.h", K_WHOLE)->body;
	co_sb_f(o, "/* generated by colorado (theme %s). Replace the matching lines of desktop/src/theme.c (needs its COLOR(hex) macro), rebuild. */\n", t->name);
	co_sb_f(o, "const unsigned int borderpx         = %d;\n", t->border_width);
	co_sb_f(o, "const float rootcolor[]             = COLOR(%s);\n", co_c32(c[CR_BG]));
	co_sb_f(o, "const float bordercolor[]           = COLOR(%s);\n", co_c32(c[CR_BORDER]));
	co_sb_f(o, "const float focuscolor[]            = COLOR(%s);\n", co_c32(c[CR_BORDER_FOCUS]));
	co_sb_f(o, "const float urgentcolor[]           = COLOR(%s);\n", co_c32(c[CR_URGENT]));
	co_sb_f(o, "const float fullscreen_bg[]         = {%.3ff, %.3ff, %.3ff, 1.0f};\n", c[CR_BG].r / 255.0, c[CR_BG].g / 255.0, c[CR_BG].b / 255.0);
	co_sb_f(o, "\n#if 0 /* desktop/src/menu.c: colors[SchemeLast][2] = { fg, bg } */\n"
		"\t[SchemeNorm] = { \"%s\", \"%s\" },\n\t[SchemeSel]  = { \"%s\", \"%s\" },\n\t[SchemeOut]  = { \"%s\", \"%s\" },\n"
		"\t[SchemeInput]  = { \"%s\", \"%s\" },\n\t[SchemePrompt] = { \"%s\", \"%s\" },\n\t[SchemeHint]   = { \"%s\", \"%s\" },\n"
		"static const char *rofi_bg       = \"%se6\";\n",
		co_h(c[CR_FG]), co_h(c[CR_BG]), co_h(c[CR_SEL_FG]), co_h(c[CR_SEL_BG]), co_h(c[CR_SEL_FG]), co_h(co_mix(c[CR_SEL_BG], c[CR_BG], 0.2)),
		co_h(c[CR_FG]), co_h(c[CR_BG]), co_h(c[CR_ACCENT]), co_h(c[CR_BG]), co_h(c[CR_FG_DIM]), co_h(c[CR_BG]), co_h(c[CR_BG]));
	co_sb_f(o, "\n/* desktop/src/bar.c */\n#define S_FOC \"%%{B%s}%%{F%s}\"\n#define S_DIM \"%%{F%s}\"\n#define S_ACC \"%%{F%s}\"\n#define F_ACC \"%%%%{F%s}\"\n",
		co_h(c[CR_ACCENT]), co_h(c[CR_ACCENT_FG]), co_h(c[CR_FG_DIM]), co_h(c[CR_WARN]), co_h(c[CR_WARN]));
	co_sb_f(o, "\n/* lemonbar standalone: lemonbar -B '%s' -F '%s' */\n#endif\n", co_h(c[CR_BG]), co_h(c[CR_FG]));
	co_sb_add(&s->notes, "desktop: fragment follows desktop/src/theme.c, menu.c and bar.c as read on this machine (theme.c part compile-checked); it is compiled in, so rebuild the desktop to use it.\n");
}
#endif
