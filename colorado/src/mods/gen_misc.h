/* gen_misc.h - cross-toolkit plumbing: xsettingsd, default cursor theme (index.theme), fontconfig snippet. stb-style single header.
 * fontconfig is verified by loading it with the real fc-match; xsettingsd and index.theme follow their documented formats, unverified.
 */
#ifndef COLORADO_GEN_MISC_H
#define COLORADO_GEN_MISC_H
#include "gen.h"

static void co_gen_xsettingsd(const co_theme *t, co_set *s) {
	co_sb *o = &co_set_block(s, "xsettingsd", W_CONFIG, "xsettingsd/xsettingsd.conf", "#", "")->body;
	if (t->gtk_theme[0]) co_sb_f(o, "Net/ThemeName \"%s\"\n", t->gtk_theme);
	co_sb_f(o, "Net/IconThemeName \"%s\"\nGtk/CursorThemeName \"%s\"\nGtk/CursorThemeSize %d\nGtk/FontName \"%s %d\"\n", t->icon_theme, t->cursor_theme, t->cursor_size, t->font, t->font_size);
	co_sb_add(&s->notes, "xsettingsd: best effort, unverified (not installed). Send SIGHUP to xsettingsd to reload (colorado does not).\n");
}

static void co_gen_cursor(const co_theme *t, co_set *s) {
	co_sb_f(&co_set_add(s, "cursor", W_HOME, ".icons/default/index.theme", K_WHOLE)->body, "[Icon Theme]\nName=Default\nComment=generated by colorado\nInherits=%s\n", t->cursor_theme);
	co_sb_add(&s->notes, "cursor: ~/.icons/default/index.theme sets the fallback cursor theme for X11 / Xcursor clients (freedesktop icon theme spec; unverified here). Wayland compositors need XCURSOR_THEME/XCURSOR_SIZE in their environment.\n");
}

static void co_gen_fontconfig(const co_theme *t, co_set *s) {
	co_sb *o = &co_set_add(s, "fontconfig", W_CONFIG, "fontconfig/conf.d/60-colorado.conf", K_WHOLE)->body;
	co_sb_f(o, "<?xml version=\"1.0\"?>\n<!DOCTYPE fontconfig SYSTEM \"urn:fontconfig:fonts.dtd\">\n<!-- generated by colorado (theme %s) -->\n<fontconfig>\n"
		"  <alias binding=\"same\"><family>sans-serif</family><prefer><family>%s</family></prefer></alias>\n"
		"  <alias binding=\"same\"><family>monospace</family><prefer><family>%s</family></prefer></alias>\n</fontconfig>\n", t->name, t->font, t->mono_font);
	co_sb_add(&s->notes, "fontconfig: loaded by the real fc-match in the tests; run `fc-cache` is not needed for alias rules.\n");
}
#endif
