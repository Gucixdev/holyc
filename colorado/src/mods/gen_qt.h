/* gen_qt.h - Qt5/Qt6 through qt5ct/qt6ct (colour scheme file + [Appearance] keys) and Kvantum (kvconfig, best effort). stb-style single header.
 *
 * qt5ct/qt6ct colour scheme: three lines active_colors/disabled_colors/inactive_colors of 21 `#aarrggbb` values in QPalette::ColorRole order
 * (WindowText Button Light Midlight Dark Mid Text BrightText ButtonText Base Window Shadow Highlight HighlightedText Link LinkVisited
 * AlternateBase NoRole ToolTipBase ToolTipText PlaceholderText) - same layout as /usr/share/qt5ct/colors/ *.conf and ~/.config/qt5ct/colors on this machine.
 * Needs QT_QPA_PLATFORMTHEME=qt5ct (resp. qt6ct) in the session environment; colorado never sets it, it prints it.
 */
#ifndef COLORADO_GEN_QT_H
#define COLORADO_GEN_QT_H
#include "gen.h"

enum { QP_N = 21 };
static void co_qt_palette(const co_theme *t, int disabled, co_rgb out[QP_N], int alpha[QP_N]) {
	const co_rgb *c = t->c; co_rgb w = co_rgb_of(255, 255, 255), k = co_rgb_of(0, 0, 0);
	co_rgb button = co_mix(c[CR_BG], c[CR_FG], 0.10), txt = disabled ? c[CR_FG_DIM] : c[CR_FG];
	co_rgb v[QP_N] = { txt, button, co_mix(button, w, 0.25), co_mix(button, w, 0.12), co_mix(button, k, 0.45), co_mix(button, k, 0.25), txt, w, txt,
		c[CR_BG_ALT], c[CR_BG], k, c[CR_SEL_BG], disabled ? c[CR_FG_DIM] : c[CR_SEL_FG], c[CR_LINK], co_mix(c[CR_LINK], c[CR_FG_DIM], 0.5),
		co_mix(c[CR_BG_ALT], c[CR_FG], 0.05), c[CR_BG], c[CR_BG_ALT], c[CR_FG], c[CR_FG_DIM] };
	for (int i = 0; i < QP_N; i++) { out[i] = v[i]; alpha[i] = 255; }
	alpha[20] = 0x80;
}

static void co_qt_scheme(const co_theme *t, co_sb *o) {
	static const char *names[3] = { "active_colors", "disabled_colors", "inactive_colors" };
	co_sb_add(o, "[ColorScheme]\n");
	for (int s = 0; s < 3; s++) {
		co_rgb v[QP_N]; int a[QP_N]; co_qt_palette(t, s == 1, v, a);
		co_sb_f(o, "%s=", names[s]);
		for (int i = 0; i < QP_N; i++) co_sb_f(o, "%s%s", co_ah(v[i], a[i]), i + 1 < QP_N ? ", " : "\n");
	}
}

static void co_qt_one(const co_theme *t, co_set *s, const char *gen, const char *dir, const char *plat) {
	char rel[160];
	snprintf(rel, sizeof rel, "%s/colors/colorado.conf", dir);
	co_qt_scheme(t, &co_set_add(s, gen, W_CONFIG, rel, K_WHOLE)->body);
	snprintf(rel, sizeof rel, "%s/%s.conf", dir, dir);
	co_file *f = co_set_ini(s, gen, W_CONFIG, rel, "Appearance");
	co_sb_f(&f->body, "color_scheme_path=%s/%s/colors/colorado.conf\ncustom_palette=true\nicon_theme=%s\n", co_cfg_root, dir, t->icon_theme);
	co_sb_f(&s->notes, "%s: needs QT_QPA_PLATFORMTHEME=%s in the session environment (colorado does not set it). Fonts are not written (qt font strings differ between Qt5/Qt6 and were not verified).\n", gen, plat);
}
static void co_gen_qt5(const co_theme *t, co_set *s) { co_qt_one(t, s, "qt5ct", "qt5ct", "qt5ct"); }
static void co_gen_qt6(const co_theme *t, co_set *s) { co_qt_one(t, s, "qt6ct", "qt6ct", "qt6ct"); }

static void co_gen_kvantum(const co_theme *t, co_set *s) {
	const co_rgb *c = t->c; co_rgb button = co_mix(c[CR_BG], c[CR_FG], 0.10);
	co_sb *o = &co_set_add(s, "kvantum", W_CONFIG, "Kvantum/colorado/colorado.kvconfig", K_WHOLE)->body;
	co_sb_f(o, "[%%General]\nauthor=colorado\ncomment=generated by colorado\n\n[GeneralColors]\nwindow.color=%s\nbase.color=%s\nalt.base.color=%s\nbutton.color=%s\n"
		"light.color=%s\nmid.light.color=%s\ndark.color=%s\nmid.color=%s\nhighlight.color=%s\ninactive.highlight.color=%s\ntext.color=%s\nwindow.text.color=%s\n"
		"button.text.color=%s\ndisabled.text.color=%s\ntooltip.base.color=%s\ntooltip.text.color=%s\nhighlight.text.color=%s\nlink.color=%s\nlink.visited.color=%s\n",
		co_h(c[CR_BG]), co_h(c[CR_BG_ALT]), co_h(co_mix(c[CR_BG_ALT], c[CR_FG], 0.05)), co_h(button), co_h(co_mix(button, co_rgb_of(255, 255, 255), 0.25)),
		co_h(co_mix(button, co_rgb_of(255, 255, 255), 0.12)), co_h(co_mix(button, co_rgb_of(0, 0, 0), 0.45)), co_h(co_mix(button, co_rgb_of(0, 0, 0), 0.25)),
		co_h(c[CR_SEL_BG]), co_h(co_mix(c[CR_SEL_BG], c[CR_BG], 0.5)), co_h(c[CR_FG]), co_h(c[CR_FG]), co_h(c[CR_FG]), co_h(c[CR_FG_DIM]), co_h(c[CR_BG_ALT]),
		co_h(c[CR_FG]), co_h(c[CR_SEL_FG]), co_h(c[CR_LINK]), co_h(co_mix(c[CR_LINK], c[CR_FG_DIM], 0.5)));
	co_sb_f(&co_set_ini(s, "kvantum", W_CONFIG, "Kvantum/kvantum.kvconfig", "General")->body, "theme=colorado\n");
	co_sb_add(&s->notes, "kvantum: best effort, unverified (Kvantum is not installed here). A kvconfig without a colorado.svg only recolours; copy a real Kvantum theme's svg next to it for the widget shapes.\n");
}
#endif
