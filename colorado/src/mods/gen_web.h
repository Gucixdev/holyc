/* gen_web.h - browsers and app runtimes: Firefox userChrome/userContent fragments, Electron/Chromium flags, flatpak overrides. stb-style single header.
 *
 * Everything here is unverified (no Firefox profile is touched, nothing is run): Firefox css goes to ~/.config/colorado/firefox/ for you to copy into
 * <profile>/chrome/ (and needs toolkit.legacyUserProfileCustomizations.stylesheets=true); Electron/Chromium and flatpak are printed notes only.
 */
#ifndef COLORADO_GEN_WEB_H
#define COLORADO_GEN_WEB_H
#include "gen.h"

static void co_gen_firefox(const co_theme *t, co_set *s) {
	const co_rgb *c = t->c; co_sb *o = &co_set_add(s, "firefox", W_CONFIG, "colorado/firefox/userChrome.css", K_WHOLE)->body;
	co_sb_f(o, "/* generated by colorado (theme %s). Copy to <profile>/chrome/userChrome.css */\n:root {\n\t--toolbar-bgcolor: %s !important;\n\t--toolbar-color: %s !important;\n"
		"\t--lwt-accent-color: %s !important;\n\t--lwt-text-color: %s !important;\n\t--tab-selected-bgcolor: %s !important;\n\t--tab-selected-textcolor: %s !important;\n"
		"\t--toolbarbutton-icon-fill: %s !important;\n\t--urlbar-box-bgcolor: %s !important;\n\t--urlbar-box-text-color: %s !important;\n\t--arrowpanel-background: %s !important;\n"
		"\t--arrowpanel-color: %s !important;\n\t--arrowpanel-border-color: %s !important;\n\t--focus-outline-color: %s !important;\n}\n"
		"#navigator-toolbox { background: %s !important; border-bottom: 1px solid %s !important; }\n",
		t->name, co_h(c[CR_BG_ALT]), co_h(c[CR_FG]), co_h(c[CR_BG]), co_h(c[CR_FG]), co_h(c[CR_ACCENT]), co_h(c[CR_ACCENT_FG]), co_h(c[CR_FG]), co_h(c[CR_BG]), co_h(c[CR_FG]),
		co_h(c[CR_BG_ALT]), co_h(c[CR_FG]), co_h(c[CR_BORDER]), co_h(c[CR_BORDER_FOCUS]), co_h(c[CR_BG]), co_h(c[CR_BORDER]));
	o = &co_set_add(s, "firefox", W_CONFIG, "colorado/firefox/userContent.css", K_WHOLE)->body;
	co_sb_f(o, "/* generated by colorado (theme %s). Copy to <profile>/chrome/userContent.css (internal pages only, never websites) */\n@-moz-document url-prefix(\"about:\") {\n:root {\n"
		"\t--in-content-page-background: %s !important;\n\t--in-content-page-color: %s !important;\n\t--in-content-box-background: %s !important;\n"
		"\t--in-content-primary-button-background: %s !important;\n\t--in-content-primary-button-text-color: %s !important;\n\t--link-color: %s !important;\n"
		"\t--in-content-border-color: %s !important;\n}\n}\n",
		t->name, co_h(c[CR_BG]), co_h(c[CR_FG]), co_h(c[CR_BG_ALT]), co_h(c[CR_ACCENT]), co_h(c[CR_ACCENT_FG]), co_h(c[CR_LINK]), co_h(c[CR_BORDER]));
	co_sb_add(&s->notes, "firefox: best effort, unverified. Copy colorado/firefox/*.css into <profile>/chrome/ and set toolkit.legacyUserProfileCustomizations.stylesheets=true in about:config.\n");
}

static void co_gen_electron(const co_theme *t, co_set *s) {
	co_sb_f(&s->notes, "electron/chromium: unverified, nothing written. Dark/light follows the GTK/portal colour scheme; force it per app with `--force-dark-mode --enable-features=WebUIDarkMode` (%s theme). "
		"Chromium-based apps read ~/.config/chromium-flags.conf / chrome-flags.conf (one flag per line) on Arch-style packages; Electron apps take the same flags on their command line.\n", t->dark ? "dark" : "light: omit the flags");
}

static void co_gen_flatpak(const co_theme *t, co_set *s) {
	(void)t;
	co_sb_add(&s->notes, "flatpak: printed, never run. Sandboxed apps do not see ~/.config by default. For all apps (user level):\n"
		"  flatpak override --user --filesystem=xdg-config/gtk-3.0:ro --filesystem=xdg-config/gtk-4.0:ro\n"
		"  flatpak override --user --filesystem=xdg-config/qt5ct:ro --filesystem=xdg-config/qt6ct:ro --env=QT_QPA_PLATFORMTHEME=qt6ct\n"
		"(flatpak override syntax checked against `flatpak override --help`; effect on apps unverified)\n");
}
#endif
