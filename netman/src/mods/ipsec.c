/* ipsec.c - strongSwan IPsec/IKEv2 module (see ipsec.h). */
#define _GNU_SOURCE
#include "ipsec.h"
#include <stdlib.h>
#include <string.h>
#include <ctype.h>
#include <errno.h>
#include <unistd.h>
#include <limits.h>

typedef struct { const char *server, *rid, *lid, *auth, *user, *pass, *psk, *cert, *key, *ca, *routes, *prop, *esp; int vip, ver; } cfg;

static int has_type(const char *t) { char ty[24]; return netman_vm_native(t, ty, sizeof ty) && !strcmp(ty, "ipsec"); }
static int yes(const char *v, int d) { return !v ? d : (!strcasecmp(v, "yes") || !strcmp(v, "1") || !strcasecmp(v, "true") || !strcasecmp(v, "on")); }
static int load(const char *text, netman_vm_prof *p, cfg *c, char *err, size_t en)
{
	if (netman_vm_parse(text, p, err, en)) return -1;
	memset(c, 0, sizeof *c);
	c->server = netman_vm_get(p, "server"); c->rid = netman_vm_get(p, "remoteid"); c->lid = netman_vm_get(p, "localid");
	c->auth = netman_vm_get(p, "auth"); c->user = netman_vm_get(p, "username"); c->pass = netman_vm_get(p, "password"); c->psk = netman_vm_get(p, "psk");
	c->cert = netman_vm_get(p, "cert"); c->key = netman_vm_get(p, "key"); c->ca = netman_vm_get(p, "ca"); c->routes = netman_vm_get(p, "routes");
	c->prop = netman_vm_get(p, "proposals"); c->esp = netman_vm_get(p, "espproposals");
	c->vip = yes(netman_vm_get(p, "virtualip"), 1);
	const char *v = netman_vm_get(p, "version"); c->ver = v ? atoi(v) : 2;
	if (!c->auth) c->auth = "eap";
	if (!c->server || !netman_vm_tok_ok(c->server)) { snprintf(err, en, "Server missing or has odd characters"); goto bad; }
	if (c->rid && !netman_vm_tok_ok(c->rid)) { snprintf(err, en, "RemoteId has odd characters"); goto bad; }
	if (c->lid && !netman_vm_tok_ok(c->lid)) { snprintf(err, en, "LocalId has odd characters"); goto bad; }
	if (c->ver != 1 && c->ver != 2) { snprintf(err, en, "Version must be 1 or 2"); goto bad; }
	if (c->prop && !netman_vm_tok_ok(c->prop)) { snprintf(err, en, "Proposals has odd characters"); goto bad; }
	if (c->esp && !netman_vm_tok_ok(c->esp)) { snprintf(err, en, "EspProposals has odd characters"); goto bad; }
	if (!strcmp(c->auth, "eap")) {
		if (!c->user || !*c->user || !netman_vm_tok_ok(c->user)) { snprintf(err, en, "Auth = eap needs Username (plain characters)"); goto bad; }
		if (!c->pass || !*c->pass) { snprintf(err, en, "Auth = eap needs Password"); goto bad; }
	} else if (!strcmp(c->auth, "psk")) {
		if (!c->psk || !*c->psk) { snprintf(err, en, "Auth = psk needs PSK"); goto bad; }
		if (c->ver == 2 && !c->lid) { snprintf(err, en, "IKEv2 with a PSK needs LocalId"); goto bad; }
	} else if (!strcmp(c->auth, "cert")) {
		if (!c->cert || !c->key || c->cert[0] != '/' || c->key[0] != '/' || !netman_vm_tok_ok(c->cert) || !netman_vm_tok_ok(c->key)) { snprintf(err, en, "Auth = cert needs absolute Cert and Key paths"); goto bad; }
		if (c->ca && (c->ca[0] != '/' || !netman_vm_tok_ok(c->ca))) { snprintf(err, en, "CA must be an absolute path"); goto bad; }
	} else { snprintf(err, en, "Auth must be eap, psk or cert"); goto bad; }
	if (c->routes) {
		char b[512], *it[32]; int n = netman_vm_split(c->routes, it, 32, b, sizeof b);
		if (n < 0) { snprintf(err, en, "Routes: too many or too long"); goto bad; }
		for (int i = 0; i < n; i++) if (netman_vm_cidr(it[i], NULL, 0, NULL, NULL)) { snprintf(err, en, "Routes: bad network %s", it[i]); goto bad; }
	}
	return 0;
bad:
	netman_vm_free(p); return -1;
}
static int detect(const char *t) { return has_type(t); }
static int validate(const char *t, char *err, size_t en) { netman_vm_prof p; cfg c; if (load(t, &p, &c, err, en)) return -1; netman_vm_free(&p); return 0; }

int netman_ipsec_gen(const char *name, const char *text, char *out, size_t n, char *err, size_t en)
{
	netman_vm_prof p; cfg c; char sec[300], ts[600] = "", conn[96]; size_t o = 0;
	if (load(text, &p, &c, err, en)) return -1;
	snprintf(conn, sizeof conn, "nm-%s", name);
	if (c.routes) {
		char b[512], *it[32]; int k = netman_vm_split(c.routes, it, 32, b, sizeof b);
		for (int i = 0; i < k; i++) snprintf(ts + strlen(ts), sizeof ts - strlen(ts), "%s%s", i ? ", " : "", it[i]);
	} else snprintf(ts, sizeof ts, "0.0.0.0/0, ::/0");
#define W(...) do { o += (size_t)snprintf(out + o, o < n ? n - o : 0, __VA_ARGS__); } while (0)
	W("# generated by netman for profile %s - do not edit\nconnections {\n    %s {\n        version = %d\n        remote_addrs = %s\n", name, conn, c.ver, c.server);
	if (c.vip && strcmp(c.auth, "psk")) W("        vips = 0.0.0.0, ::\n");
	if (c.prop) W("        proposals = %s\n", c.prop);
	W("        dpd_delay = 30s\n        local {\n");
	if (!strcmp(c.auth, "eap")) W("            auth = eap\n            eap_id = %s\n", c.user);
	else if (!strcmp(c.auth, "psk")) { W("            auth = psk\n"); if (c.lid) W("            id = %s\n", c.lid); }
	else { W("            auth = pubkey\n            certs = %s\n", c.cert); if (c.lid) W("            id = %s\n", c.lid); }
	W("        }\n        remote {\n            auth = %s\n            id = %s\n", !strcmp(c.auth, "psk") ? "psk" : "pubkey", c.rid ? c.rid : c.server);
	if (c.ca && !strcmp(c.auth, "cert")) W("            cacerts = %s\n", c.ca);
	W("        }\n        children {\n            %s {\n                remote_ts = %s\n", conn, ts);
	if (c.esp) W("                esp_proposals = %s\n", c.esp);
	W("                start_action = none\n                dpd_action = restart\n                close_action = none\n            }\n        }\n    }\n}\nsecrets {\n");
	if (!strcmp(c.auth, "eap")) { netman_vm_hex(c.pass, sec, sizeof sec); W("    eap-%s {\n        id = %s\n        secret = %s\n    }\n", conn, c.user, sec); }
	else if (!strcmp(c.auth, "psk")) { netman_vm_hex(c.psk, sec, sizeof sec); W("    ike-%s {\n        id = %s\n        secret = %s\n    }\n", conn, c.rid ? c.rid : c.server, sec); }
	else W("    private-%s {\n        file = %s\n    }\n", conn, c.key);
	W("}\n");
#undef W
	netman_vm_free(&p);
	if (o >= n) { snprintf(err, en, "config too large"); return -1; }
	return 0;
}

static const char *state(const netman_vm_ctx *cx, const char *name)
{
	char conn[96], o[4096]; int st = 0;
	snprintf(conn, sizeof conn, "nm-%s", name);
	char *av[] = { "swanctl", "--list-sas", "--ike", conn, NULL };
	if (netman_vm_run(av, NULL, o, sizeof o, 5000, &st) || st) return netman_vm_log_has(cx, name, "AUTH_FAILED") ? "auth failed" : "down";
	if (strstr(o, "ESTABLISHED") && strstr(o, "INSTALLED")) return "connected";
	if (strstr(o, "ESTABLISHED") || strstr(o, "CONNECTING")) return "connecting";
	return "down";
}
static int up(const netman_vm_ctx *cx, const char *name, const char *path, const char *text, int wait)
{
	char sw[PATH_MAX], err[160], *conf = malloc(16384), cp[PATH_MAX], lf[PATH_MAX], conn[96], to[16]; int rc = 1, st = 0; (void)path;
	if (!conf) return 1;
	if (!netman_vm_which("swanctl", sw, sizeof sw)) { free(conf); return netman_vm_fail(cx, "%s: swanctl not found (install strongSwan; charon-cmd is not supported, it prompts on a terminal)", name); }
	if (netman_ipsec_gen(name, text, conf, 16384, err, sizeof err)) { free(conf); return netman_vm_fail(cx, "%s: %s", name, err); }
	if (netman_vm_mkdirs(cx->run_dir, 0700)) { free(conf); return netman_vm_fail(cx, "%s: %s", cx->run_dir, strerror(errno)); }
	netman_vm_path(cp, sizeof cp, cx, name, "swanctl.conf"); netman_vm_path(lf, sizeof lf, cx, name, "log");
	snprintf(conn, sizeof conn, "nm-%s", name); snprintf(to, sizeof to, "%d", wait > 0 ? wait : 30);
	if (netman_vm_write(cp, conf, strlen(conf), 0600)) { explicit_bzero(conf, 16384); free(conf); return netman_vm_fail(cx, "%s: %s", cp, strerror(errno)); }
	explicit_bzero(conf, 16384); free(conf);
	unlink(lf);
	{ char *av[] = { "swanctl", "--load-all", "--file", cp, NULL }; st = netman_vm_spawn(av, NULL, lf); }
	if (st) { unlink(cp); return netman_vm_fail(cx, "%s: swanctl --load-all failed (exit %d; is charon running? see `netman vpn logs %s`)", name, st, name); }
	{ char *av[] = { "swanctl", "--initiate", "--child", conn, "--timeout", to, NULL }; st = netman_vm_spawn(av, NULL, lf); }
	if (st) { char *tv[] = { "swanctl", "--terminate", "--ike", conn, NULL }; netman_vm_spawn(tv, NULL, lf); unlink(cp); return netman_vm_fail(cx, "%s: could not establish the tunnel (swanctl exit %d; see `netman vpn logs %s`)", name, st, name); }
	netman_vm_msg(cx, "%s: connected", name); rc = 0;
	return rc;
}
static int down(const netman_vm_ctx *cx, const char *name, const char *text)
{
	char conn[96], cp[PATH_MAX], lf[PATH_MAX]; (void)text;
	snprintf(conn, sizeof conn, "nm-%s", name); netman_vm_path(cp, sizeof cp, cx, name, "swanctl.conf"); netman_vm_path(lf, sizeof lf, cx, name, "log");
	char *av[] = { "swanctl", "--terminate", "--ike", conn, NULL };
	int st = netman_vm_spawn(av, NULL, lf);
	unlink(cp);
	if (st) return netman_vm_fail(cx, "%s: swanctl --terminate failed (exit %d): not running?", name, st);
	netman_vm_msg(cx, "%s: down", name); return 0;
}
static int ks(const char *text, char lines[][160], int max, char *tun, size_t tunn, const char *name)
{
	netman_vm_prof p; cfg c; char err[64]; int n; (void)name;
	tun[0] = 0; (void)tunn;
	if (load(text, &p, &c, err, sizeof err)) return -1;
	n = netman_vm_ks_host(c.server, lines, max - 1, "");
	if (n > 0) snprintf(lines[n++], 160, "rt ipsec exists accept");
	netman_vm_free(&p); return n;
}
static int info(const netman_vm_ctx *cx, const char *name, const char *text)
{
	netman_vm_prof p; cfg c; char err[96];
	netman_vm_msg(cx, "type         ipsec (strongSwan)");
	netman_vm_msg(cx, "state        %s", state(cx, name));
	if (load(text, &p, &c, err, sizeof err)) { netman_vm_msg(cx, "config       %s", err); return 0; }
	netman_vm_msg(cx, "server       %s", c.server);
	netman_vm_msg(cx, "auth         %s", c.auth);
	netman_vm_msg(cx, "routing      %s", c.routes ? "split tunnel (only Routes go through the VPN)" : "full tunnel (0.0.0.0/0, ::/0)");
	if (c.routes) netman_vm_msg(cx, "routes       %s", c.routes);
	netman_vm_free(&p); return 0;
}
const netman_vpnmod netman_ipsec_mod = { "ipsec", ".vpn", "swanctl", "vpn.ipsec", detect, validate, netman_ipsec_gen, up, down, state, ks, info };
