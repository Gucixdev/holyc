#define _GNU_SOURCE
#include "openconnect.h"
#include <stdlib.h>
#include <string.h>
#include <ctype.h>
#include <errno.h>
#include <unistd.h>
#include <signal.h>
#include <limits.h>
#include <net/if.h>
#include <arpa/inet.h>

static const char *const protos[] = { "anyconnect", "gp", "nc", "pulse", "f5", "fortinet", "array", NULL };
static const char *const scripts[] = { "/usr/share/vpnc-scripts/vpnc-script", "/etc/vpnc/vpnc-script", "/usr/libexec/openconnect/vpnc-script", "/usr/lib/openconnect/vpnc-script", NULL };
typedef struct { const char *server, *proto, *user, *pass, *group, *pin, *ca, *cert, *key, *routes, *script; } cfg;

static int detect(const char *t) { char ty[24]; return netman_vm_native(t, ty, sizeof ty) && !strcmp(ty, "openconnect"); }
static int load(const char *text, netman_vm_prof *p, cfg *c, char *err, size_t en)
{
	if (netman_vm_parse(text, p, err, en)) return -1;
	memset(c, 0, sizeof *c);
	c->server = netman_vm_get(p, "server"); c->proto = netman_vm_get(p, "protocol"); c->user = netman_vm_get(p, "username"); c->pass = netman_vm_get(p, "password");
	c->group = netman_vm_get(p, "authgroup"); c->pin = netman_vm_get(p, "servercert"); c->ca = netman_vm_get(p, "ca"); c->cert = netman_vm_get(p, "cert");
	c->key = netman_vm_get(p, "key"); c->routes = netman_vm_get(p, "routes"); c->script = netman_vm_get(p, "script");
	if (!c->proto) c->proto = "anyconnect";
	int ok = 0; for (int i = 0; protos[i]; i++) if (!strcasecmp(c->proto, protos[i])) ok = 1;
	if (!ok) { snprintf(err, en, "Protocol must be one of anyconnect gp nc pulse f5 fortinet array"); goto bad; }
	if (!c->server || !netman_vm_tok_ok(c->server) || c->server[0] == '-') { snprintf(err, en, "Server missing or has odd characters"); goto bad; }
	if (c->user && (!netman_vm_tok_ok(c->user) || c->user[0] == '-')) { snprintf(err, en, "Username has odd characters"); goto bad; }
	if (c->group && !netman_vm_tok_ok(c->group)) { snprintf(err, en, "AuthGroup has odd characters"); goto bad; }
	if (c->pin && (strncmp(c->pin, "pin-sha256:", 11) || !netman_vm_tok_ok(c->pin))) { snprintf(err, en, "ServerCert must look like pin-sha256:BASE64"); goto bad; }
	if ((c->ca && (c->ca[0] != '/' || !netman_vm_tok_ok(c->ca))) || (c->cert && (c->cert[0] != '/' || !netman_vm_tok_ok(c->cert))) || (c->key && (c->key[0] != '/' || !netman_vm_tok_ok(c->key)))) { snprintf(err, en, "CA, Cert and Key must be absolute paths"); goto bad; }
	if (c->script && (c->script[0] != '/' || !netman_vm_tok_ok(c->script))) { snprintf(err, en, "Script must be an absolute path"); goto bad; }
	if (!c->user && !c->cert) { snprintf(err, en, "needs Username (with Password) or Cert"); goto bad; }
	if (c->routes) {
		char b[512], *it[32]; int n = netman_vm_split(c->routes, it, 32, b, sizeof b);
		if (n < 0) { snprintf(err, en, "Routes: too many or too long"); goto bad; }
		for (int i = 0; i < n; i++) if (netman_vm_cidr(it[i], NULL, 0, NULL, NULL)) { snprintf(err, en, "Routes: bad network %s", it[i]); goto bad; }
	}
	return 0;
bad:
	netman_vm_free(p); return -1;
}
static int validate(const char *t, char *err, size_t en) { netman_vm_prof p; cfg c; if (load(t, &p, &c, err, en)) return -1; netman_vm_free(&p); return 0; }

static const char *vpnc(const cfg *c) { if (c->script) return c->script; for (int i = 0; scripts[i]; i++) if (access(scripts[i], X_OK) == 0) return scripts[i]; return scripts[0]; }
int netman_oc_script(const char *text, char *out, size_t n, char *err, size_t en)
{
	netman_vm_prof p; cfg c; size_t o = 0; int n4 = 0, n6 = 0; char b[512], *it[32];
	if (load(text, &p, &c, err, en)) return -1;
	out[0] = 0;
	if (!c.routes) { netman_vm_free(&p); return 0; }
	int k = netman_vm_split(c.routes, it, 32, b, sizeof b);
	o += (size_t)snprintf(out + o, n - o, "#!/bin/sh\n# generated by netman: split tunnel, only these networks go through the VPN (overrides the server's list)\n");
	for (int i = 0; i < k && o + 200 < n; i++) {
		char ip[64]; int pf, fam; netman_vm_cidr(it[i], ip, sizeof ip, &pf, &fam);
		if (fam == AF_INET) {
			unsigned m = pf ? 0xffffffffu << (32 - pf) : 0;
			o += (size_t)snprintf(out + o, n - o, "export CISCO_SPLIT_INC_%d_ADDR=%s CISCO_SPLIT_INC_%d_MASK=%u.%u.%u.%u CISCO_SPLIT_INC_%d_MASKLEN=%d\n", n4, ip, n4, m >> 24, (m >> 16) & 255, (m >> 8) & 255, m & 255, n4, pf);
			n4++;
		} else {
			o += (size_t)snprintf(out + o, n - o, "export CISCO_IPV6_SPLIT_INC_%d_ADDR=%s CISCO_IPV6_SPLIT_INC_%d_MASKLEN=%d\n", n6, ip, n6, pf);
			n6++;
		}
	}
	if (n4) o += (size_t)snprintf(out + o, n - o, "export CISCO_SPLIT_INC=%d\n", n4);
	if (n6) o += (size_t)snprintf(out + o, n - o, "export CISCO_IPV6_SPLIT_INC=%d\n", n6);
	o += (size_t)snprintf(out + o, n - o, "exec %s \"$@\"\n", vpnc(&c));
	netman_vm_free(&p);
	if (o >= n) { snprintf(err, en, "script too large"); return -1; }
	return 0;
}

/* argv storage lives as long as the process: the golden test and `up` both use it right away */
int netman_oc_args(const char *name, const char *text, const netman_vm_ctx *cx, char *av[], int max, char *err, size_t en)
{
	static char proto[40], user[300], group[300], pin[300], ca[PATH_MAX + 12], cert[PATH_MAX + 14], key[PATH_MAX + 12], ifn[20], iff[40], pf[PATH_MAX], scr[PATH_MAX + 12];
	netman_vm_prof p; cfg c; int n = 0; (void)max;
	if (load(text, &p, &c, err, en)) return -1;
	netman_vm_ifname("oc-", name, ifn, sizeof ifn); netman_vm_path(pf, sizeof pf, cx, name, "pid");
	snprintf(proto, sizeof proto, "--protocol=%s", c.proto); snprintf(iff, sizeof iff, "--interface=%s", ifn);
	av[n++] = "openconnect"; av[n++] = "--background"; av[n++] = "--non-inter"; av[n++] = "--pid-file"; av[n++] = pf; av[n++] = proto; av[n++] = iff;
	if (c.user) { snprintf(user, sizeof user, "--user=%s", c.user); av[n++] = user; }
	if (c.pass) av[n++] = "--passwd-on-stdin";                       /* the password itself is written to stdin by up() */
	if (c.group) { snprintf(group, sizeof group, "--authgroup=%s", c.group); av[n++] = group; }
	if (c.pin) { snprintf(pin, sizeof pin, "--servercert=%s", c.pin); av[n++] = pin; }
	if (c.ca) { snprintf(ca, sizeof ca, "--cafile=%s", c.ca); av[n++] = ca; }
	if (c.cert) { snprintf(cert, sizeof cert, "--certificate=%s", c.cert); av[n++] = cert; }
	if (c.key) { snprintf(key, sizeof key, "--sslkey=%s", c.key); av[n++] = key; }
	if (c.routes) { char sp[PATH_MAX]; netman_vm_path(sp, sizeof sp, cx, name, "script"); snprintf(scr, sizeof scr, "--script=%s", sp); av[n++] = scr; }
	else if (c.script) { snprintf(scr, sizeof scr, "--script=%s", c.script); av[n++] = scr; }
	av[n++] = "--"; av[n++] = (char *)c.server;
	av[n] = NULL;
	char *srv = av[n - 1]; static char srvbuf[300]; snprintf(srvbuf, sizeof srvbuf, "%s", srv); av[n - 1] = srvbuf;
	netman_vm_free(&p);
	return n;
}

static int running(const netman_vm_ctx *cx, const char *name, int *pid) { char pf[PATH_MAX]; netman_vm_path(pf, sizeof pf, cx, name, "pid"); return netman_vm_pid_alive(pf, pf, pid); }
static const char *state(const netman_vm_ctx *cx, const char *name)
{
	char ifn[20]; netman_vm_ifname("oc-", name, ifn, sizeof ifn);
	if (!running(cx, name, NULL)) return netman_vm_log_has(cx, name, "ailed to complete authentication") || netman_vm_log_has(cx, name, "Login failed") ? "auth failed" : "down";
	return if_nametoindex(ifn) ? "connected" : "connecting";
}
static int up(const netman_vm_ctx *cx, const char *name, const char *path, const char *text, int wait)
{
	char bin[PATH_MAX], err[160], lf[PATH_MAX], *av[40]; (void)path;
	if (running(cx, name, NULL)) return netman_vm_fail(cx, "%s is already running", name);
	if (!netman_vm_which("openconnect", bin, sizeof bin)) return netman_vm_fail(cx, "%s: openconnect not found (install it; netman only drives the binary)", name);
	if (netman_vm_mkdirs(cx->run_dir, 0700)) return netman_vm_fail(cx, "%s: %s", cx->run_dir, strerror(errno));
	netman_vm_path(lf, sizeof lf, cx, name, "log"); unlink(lf);
	char *scr = malloc(8192); if (!scr) return 1;
	if (netman_oc_script(text, scr, 8192, err, sizeof err)) { free(scr); return netman_vm_fail(cx, "%s: %s", name, err); }
	if (scr[0]) { char sp[PATH_MAX]; netman_vm_path(sp, sizeof sp, cx, name, "script"); if (netman_vm_write(sp, scr, strlen(scr), 0700)) { free(scr); return netman_vm_fail(cx, "%s: %s", sp, strerror(errno)); } }
	free(scr);
	if (netman_oc_args(name, text, cx, av, 40, err, sizeof err) < 0) return netman_vm_fail(cx, "%s: %s", name, err);
	netman_vm_prof p; netman_vm_parse(text, &p, err, sizeof err);
	char pw[600]; const char *pass = netman_vm_get(&p, "password");
	snprintf(pw, sizeof pw, "%s\n", pass ? pass : "");
	int rc = netman_vm_spawn(av, pass ? pw : NULL, lf);
	explicit_bzero(pw, sizeof pw); netman_vm_free(&p);
	if (rc != 0) return netman_vm_fail(cx, "%s: openconnect failed (exit %d)%s; see `netman vpn logs %s`", name, rc, netman_vm_log_has(cx, name, "ailed to complete authentication") ? ": authentication failed" : "", name);
	for (int i = 0; i < (wait > 0 ? wait : 30) * 5; i++) {
		const char *s = state(cx, name);
		if (!strcmp(s, "connected")) { netman_vm_msg(cx, "%s: connected", name); return 0; }
		if (!strcmp(s, "down") && i >= 10) return netman_vm_fail(cx, "%s: openconnect exited; see `netman vpn logs %s`", name, name);
		usleep(200000);
	}
	netman_vm_msg(cx, "%s: %s", name, state(cx, name));
	return 0;
}
static int down(const netman_vm_ctx *cx, const char *name, const char *text)
{
	int pid; char pf[PATH_MAX], sp[PATH_MAX]; (void)text;
	netman_vm_path(pf, sizeof pf, cx, name, "pid"); netman_vm_path(sp, sizeof sp, cx, name, "script");
	if (!running(cx, name, &pid)) { unlink(pf); unlink(sp); return netman_vm_fail(cx, "%s is not running", name); }
	kill(pid, SIGTERM);                                           /* openconnect runs vpnc-script's disconnect (routes, DNS) itself */
	for (int i = 0; i < 40 && kill(pid, 0) == 0; i++) usleep(200000);
	if (kill(pid, 0) == 0) { kill(pid, SIGKILL); usleep(200000); }
	unlink(pf); unlink(sp);
	netman_vm_msg(cx, "%s: down", name);
	return 0;
}
static int ks(const char *text, char lines[][160], int max, char *tun, size_t tunn, const char *name)
{
	netman_vm_prof p; cfg c; char err[64], h[300]; int n;
	if (load(text, &p, &c, err, sizeof err)) return -1;
	netman_vm_ifname("oc-", name, tun, tunn);
	const char *s = c.server; if (!strncmp(s, "https://", 8)) s += 8;
	snprintf(h, sizeof h, "%s", s); h[strcspn(h, "/")] = 0;
	if (h[0] == '[') { memmove(h, h + 1, strlen(h)); char *e = strchr(h, ']'); if (e) *e = 0; }
	else { char *col = strchr(h, ':'); if (col && !strchr(col + 1, ':')) *col = 0; }
	n = netman_vm_ks_host(h, lines, max, "");
	netman_vm_free(&p); return n;
}
static int info(const netman_vm_ctx *cx, const char *name, const char *text)
{
	netman_vm_prof p; cfg c; char err[96], ifn[20]; netman_vm_ifname("oc-", name, ifn, sizeof ifn);
	netman_vm_msg(cx, "type         openconnect");
	netman_vm_msg(cx, "state        %s", state(cx, name));
	if (load(text, &p, &c, err, sizeof err)) { netman_vm_msg(cx, "config       %s", err); return 0; }
	netman_vm_msg(cx, "server       %s", c.server); netman_vm_msg(cx, "protocol     %s", c.proto); netman_vm_msg(cx, "interface    %s", ifn);
	netman_vm_msg(cx, "routing      %s", c.routes ? "split tunnel (Routes override the server's list)" : "as the server says (usually full tunnel)");
	netman_vm_free(&p); return 0;
}
const netman_vpnmod netman_openconnect_mod = { "openconnect", ".vpn", "openconnect", "vpn.openconnect", detect, validate, NULL, up, down, state, ks, info };
