#define SAY(c, ...) do { fprintf((c)->out ? (c)->out : stdout, __VA_ARGS__); fputc('\n', (c)->out ? (c)->out : stdout); } while (0)
static int fail(const netman_tor_cfg *c, const char *f, ...)
{
	va_list a; va_start(a, f); FILE *e = c->err ? c->err : stderr; fputs("netman tor: ", e); vfprintf(e, f, a); fputc('\n', e); va_end(a); return 1;
}
typedef struct { char *s; size_t n, cap; int bad; } sb;
static void sp(sb *b, const char *f, ...)
{
	va_list a; va_start(a, f); int k = vsnprintf(b->s + b->n, b->cap - b->n, f, a); va_end(a);
	if (k < 0 || (size_t)k >= b->cap - b->n) { b->bad = 1; if (b->cap) b->s[b->n] = 0; return; }
	b->n += (size_t)k;
}

void netman_tor_defaults(netman_tor_cfg *c)
{
	memset(c, 0, sizeof *c);
	snprintf(c->dir, sizeof c->dir, "/run/netman/tor"); snprintf(c->persist, sizeof c->persist, "/etc/netman/tor.conf");
	snprintf(c->mode, sizeof c->mode, "transparent"); snprintf(c->tor_user, sizeof c->tor_user, "tor");
	snprintf(c->obfs4_bin, sizeof c->obfs4_bin, "obfs4proxy"); snprintf(c->snowflake_bin, sizeof c->snowflake_bin, "snowflake-client");
	c->socks_port = 9050; c->trans_port = 9040; c->dns_port = 5353; c->control_port = 0;
}

/* ---- validation ----------------------------------------------------------------------------------------------------- */
static int word_ok(const char *s) { if (!*s) return 0; for (; *s; s++) if (!(isalnum((unsigned char)*s) || strchr("_.-/", *s))) return 0; return 1; }
static int list_ok(const char *s, int ifaces)   /* "1000, 1001" or "wlan0 eth1" */
{
	for (; *s; s++) if (!(isalnum((unsigned char)*s) || *s == ',' || *s == ' ' || (ifaces && strchr("_.-", *s)))) return 0;
	return 1;
}
static int port_ok(int p) { return p > 0 && p < 65536; }
int netman_tor_validate(const netman_tor_cfg *c, char *err, size_t en)
{
#define BAD(...) do { snprintf(err, en, __VA_ARGS__); return -1; } while (0)
	if (strcmp(c->mode, "transparent") && strcmp(c->mode, "socks")) BAD("mode must be transparent or socks");
	if (!word_ok(c->dir) || c->dir[0] != '/') BAD("tor.dir must be an absolute path of plain characters");
	if (!word_ok(c->tor_user)) BAD("bad tor.user");
	if (!port_ok(c->socks_port) || !port_ok(c->trans_port) || !port_ok(c->dns_port) || c->control_port < 0 || c->control_port > 65535) BAD("bad port");
	if (c->socks_port == c->trans_port || c->socks_port == c->dns_port || c->trans_port == c->dns_port) BAD("socks, trans and dns ports must differ");
	if (!list_ok(c->route_uids, 0)) BAD("tor.route_uids: numbers separated by commas");
	if (!list_ok(c->route_ifaces, 1)) BAD("tor.route_ifaces: interface names");
	if (c->exit_cc[0] && !(strlen(c->exit_cc) == 2 && isalpha((unsigned char)c->exit_cc[0]) && isalpha((unsigned char)c->exit_cc[1]))) BAD("exit country must be two letters (de, nl, ...)");
	if (!word_ok(c->obfs4_bin) || !word_ok(c->snowflake_bin)) BAD("bad transport binary");
	for (int i = 0; i < c->nbridges; i++) {
		const char *b = c->bridges[i];
		for (const char *p = b; *p; p++) if ((unsigned char)*p < 32 || strchr("\"'\\;`$", *p)) BAD("bridge line %d has a character that is not allowed", i + 1);
		if (strncmp(b, "obfs4 ", 6) && strncmp(b, "snowflake ", 10) && strncmp(b, "meek", 4) && !isdigit((unsigned char)b[0]) && b[0] != '[') BAD("bridge line %d: expected 'obfs4 ADDR:PORT FINGERPRINT cert=... iat-mode=0', 'snowflake ...' or a plain ADDR:PORT", i + 1);
	}
	for (int i = 0; i < c->nhs; i++) {
		if (!word_ok(c->hs[i].name) || strchr(c->hs[i].name, '/')) BAD("hidden service name %d", i + 1);
		if (!port_ok(c->hs[i].port)) BAD("hidden service %s: bad port", c->hs[i].name);
		if (!netman_vm_tok_ok(c->hs[i].target) || !strchr(c->hs[i].target, ':')) BAD("hidden service %s: target must be host:port", c->hs[i].name);
	}
	return 0;
#undef BAD
}

/* ---- generated files --------------------------------------------------------------------------------------------------- */
int netman_tor_torrc(const netman_tor_cfg *c, char *buf, size_t n)
{
	sb b = { buf, 0, n, 0 };
	sp(&b, "# generated by netman - rewritten on every `netman tor up`, do not edit\n");
	sp(&b, "DataDirectory %s/data\nPidFile %s/tor.pid\nLog notice file %s/tor.log\nClientOnly 1\nAvoidDiskWrites 1\n", c->dir, c->dir, c->dir);
	sp(&b, "SocksPort 127.0.0.1:%d IsolateDestAddr\n", c->socks_port);
	if (!strcmp(c->mode, "transparent")) {
		sp(&b, "TransPort 127.0.0.1:%d IsolateDestAddr\nDNSPort 127.0.0.1:%d\nAutomapHostsOnResolve 1\n", c->trans_port, c->dns_port);
	}
	if (c->control_port) sp(&b, "ControlPort 127.0.0.1:%d\n", c->control_port); else sp(&b, "ControlSocket %s/control\n", c->dir);
	sp(&b, "CookieAuthentication 1\nCookieAuthFile %s/control_auth_cookie\nCookieAuthFileGroupReadable 0\n", c->dir);
	if (c->nbridges) {
		int ob = 0, sn = 0;
		for (int i = 0; i < c->nbridges; i++) { if (!strncmp(c->bridges[i], "obfs4 ", 6)) ob = 1; if (!strncmp(c->bridges[i], "snowflake ", 10)) sn = 1; }
		sp(&b, "UseBridges 1\n");
		if (ob) sp(&b, "ClientTransportPlugin obfs4 exec %s\n", c->obfs4_bin);
		if (sn) sp(&b, "ClientTransportPlugin snowflake exec %s\n", c->snowflake_bin);
		for (int i = 0; i < c->nbridges; i++) sp(&b, "Bridge %s\n", c->bridges[i]);
	}
	if (c->exit_cc[0]) {
		char cc[8]; snprintf(cc, sizeof cc, "%s", c->exit_cc); for (char *p = cc; *p; p++) *p = (char)tolower((unsigned char)*p);
		sp(&b, "ExitNodes {%s}\n", cc); if (c->strict) sp(&b, "StrictNodes 1\n");
	}
	for (int i = 0; i < c->nhs; i++) sp(&b, "HiddenServiceDir %s/hs/%s\nHiddenServicePort %d %s\n", c->dir, c->hs[i].name, c->hs[i].port, c->hs[i].target);
	return b.bad ? -1 : 0;
}

static void nft_set(sb *b, const char *list, int quote)    /* "a, b" -> `{ a, b }` */
{
	char t[128]; int first = 1; snprintf(t, sizeof t, "%s", list); sp(b, "{ ");
	for (char *p = t, *sv = NULL, *x = strtok_r(p, ", ", &sv); x; x = strtok_r(NULL, ", ", &sv)) { sp(b, quote ? "%s\"%s\"" : "%s%s", first ? "" : ", ", x); first = 0; }
	sp(b, " }");
}
int netman_tor_nft(const netman_tor_cfg *c, unsigned uid, char *buf, size_t n)
{
	sb b = { buf, 0, n, 0 };
	int uids = c->route_uids[0] != 0, ifs = c->route_ifaces[0] != 0;
	sp(&b, "table inet netman_tor\ndelete table inet netman_tor\ntable inet netman_tor {\n");
	sp(&b, "\tchain nat_out {\n\t\ttype nat hook output priority -100; policy accept;\n\t\tmeta skuid %u return\n", uid);
	if (uids) { sp(&b, "\t\tmeta skuid != "); nft_set(&b, c->route_uids, 0); sp(&b, " return\n"); }
	sp(&b, "\t\tudp dport 53 redirect to :%d\n\t\ttcp dport 53 redirect to :%d\n", c->dns_port, c->dns_port);
	sp(&b, "\t\tip daddr 127.0.0.0/8 return\n\t\tip6 daddr ::1 return\n");
	sp(&b, "\t\tmeta l4proto tcp tcp flags & (syn | ack) == syn redirect to :%d\n\t}\n", c->trans_port);
	sp(&b, "\tchain filter_out {\n\t\ttype filter hook output priority 0; policy accept;\n\t\tmeta skuid %u accept\n", uid);
	if (uids) { sp(&b, "\t\tmeta skuid != "); nft_set(&b, c->route_uids, 0); sp(&b, " accept\n"); }
	sp(&b, "\t\tip daddr 127.0.0.1 tcp dport { %d, %d, %d } accept\n", c->trans_port, c->socks_port, c->dns_port);
	sp(&b, "\t\tip daddr 127.0.0.1 udp dport %d accept\n", c->dns_port);
	sp(&b, "\t\tip saddr 127.0.0.1 tcp sport { %d, %d } accept\n\t\tip saddr 127.0.0.1 udp sport %d accept\n", c->trans_port, c->socks_port, c->dns_port);   /* replies of redirected flows (SYN-ACK, RST, DNS answers) */
	sp(&b, "\t\tcounter drop\n\t}\n");
	if (ifs) {
		sp(&b, "\tchain nat_pre {\n\t\ttype nat hook prerouting priority -100; policy accept;\n\t\tiifname "); nft_set(&b, c->route_ifaces, 1);
		sp(&b, " udp dport 53 redirect to :%d\n\t\tiifname ", c->dns_port); nft_set(&b, c->route_ifaces, 1);
		sp(&b, " tcp dport 53 redirect to :%d\n\t\tiifname ", c->dns_port); nft_set(&b, c->route_ifaces, 1);
		sp(&b, " meta l4proto tcp tcp flags & (syn | ack) == syn redirect to :%d\n\t}\n", c->trans_port);
		sp(&b, "\tchain filter_fwd {\n\t\ttype filter hook forward priority 0; policy accept;\n\t\tiifname "); nft_set(&b, c->route_ifaces, 1);
		sp(&b, " counter drop\n\t}\n");
		sp(&b, "\tchain filter_in {\n\t\ttype filter hook input priority 0; policy accept;\n\t\tiifname "); nft_set(&b, c->route_ifaces, 1);
		sp(&b, " tcp dport { %d, %d } accept\n\t\tiifname ", c->trans_port, c->socks_port); nft_set(&b, c->route_ifaces, 1);
		sp(&b, " udp dport %d accept\n\t}\n", c->dns_port);
	}
	sp(&b, "}\n");
	return b.bad ? -1 : 0;
}

/* ---- control port client -------------------------------------------------------------------------------------------------- */
int netman_tor_ctl_open(netman_tor_ctl *t, const char *addr)
{
	memset(t, 0, sizeof *t); t->fd = -1;
	if (!strncmp(addr, "unix:", 5)) {
		struct sockaddr_un u; memset(&u, 0, sizeof u); u.sun_family = AF_UNIX;
		if (strlen(addr + 5) >= sizeof u.sun_path) return -1;
		strcpy(u.sun_path, addr + 5);
		t->fd = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC, 0); if (t->fd < 0) return -1;
		if (connect(t->fd, (struct sockaddr *)&u, sizeof u)) { close(t->fd); t->fd = -1; return -1; }
		return 0;
	}
	char h[64]; int port; if (sscanf(addr, "%63[^:]:%d", h, &port) != 2) return -1;
	struct sockaddr_in a; memset(&a, 0, sizeof a); a.sin_family = AF_INET; a.sin_port = htons((uint16_t)port);
	if (inet_pton(AF_INET, h, &a.sin_addr) != 1) return -1;
	t->fd = socket(AF_INET, SOCK_STREAM | SOCK_CLOEXEC, 0); if (t->fd < 0) return -1;
	if (connect(t->fd, (struct sockaddr *)&a, sizeof a)) { close(t->fd); t->fd = -1; return -1; }
	return 0;
}
void netman_tor_ctl_close(netman_tor_ctl *t) { if (t->fd >= 0) close(t->fd); t->fd = -1; }
static int ctl_line(netman_tor_ctl *t, char *line, size_t n)     /* one CRLF line, -1 on io error / timeout (5s) */
{
	for (;;) {
		char *nl = memchr(t->buf, '\n', t->have);
		if (nl) {
			size_t l = (size_t)(nl - t->buf), k = l && t->buf[l - 1] == '\r' ? l - 1 : l;
			if (k >= n) k = n - 1;
			memcpy(line, t->buf, k); line[k] = 0;
			memmove(t->buf, nl + 1, t->have - l - 1); t->have -= l + 1; return (int)k;
		}
		if (t->have == sizeof t->buf) return -1;
		struct pollfd p = { t->fd, POLLIN, 0 }; if (poll(&p, 1, 5000) <= 0) return -1;
		ssize_t r = read(t->fd, t->buf + t->have, sizeof t->buf - t->have);
		if (r <= 0) { if (r < 0 && errno == EINTR) continue; return -1; }
		t->have += (size_t)r;
	}
}
int netman_tor_ctl_cmd(netman_tor_ctl *t, const char *cmd, char *reply, size_t n)
{
	size_t l = strlen(cmd), off = 0; char line[1024]; int code = -1, data = 0;
	if (strpbrk(cmd, "\r\n")) return -1;                     /* never let a value smuggle a second command */
	char *w = malloc(l + 3); if (!w) return -1; memcpy(w, cmd, l); memcpy(w + l, "\r\n", 3);
	while (off < l + 2) { ssize_t k = write(t->fd, w + off, l + 2 - off); if (k < 0) { if (errno == EINTR) continue; free(w); return -1; } off += (size_t)k; }
	free(w);
	if (n) reply[0] = 0;
	size_t rl = 0;
	for (;;) {
		int k = ctl_line(t, line, sizeof line); if (k < 0) return -1;
		if (data) { if (!strcmp(line, ".")) { data = 0; continue; } }
		else {
			if (k < 4 || !isdigit((unsigned char)line[0])) return -1;
			code = atoi(line);
			if (line[3] == '+') data = 1;
		}
		if (n && rl + (size_t)k + 2 < n) { memcpy(reply + rl, data && line[3] == '+' ? line : line, (size_t)k); rl += (size_t)k; reply[rl++] = '\n'; reply[rl] = 0; }
		if (!data && line[3] == ' ') return code;
	}
}
int netman_tor_ctl_auth(netman_tor_ctl *t)
{
	char rep[2048], cmd[256], *p; int rc = netman_tor_ctl_cmd(t, "PROTOCOLINFO 1", rep, sizeof rep);
	if (rc != 250) return -1;
	if (!strstr(rep, "COOKIE")) return -1;                   /* only cookie auth is supported: no password is ever stored */
	p = strstr(rep, "COOKIEFILE=\""); if (!p) return -1;
	p += 12; char path[256]; size_t k = strcspn(p, "\""); if (k >= sizeof path) return -1; memcpy(path, p, k); path[k] = 0;
	size_t cl = 0; char *ck = netman_vm_slurp(path, &cl, 64);
	if (!ck || cl != 32) { free(ck); return -1; }
	int o = snprintf(cmd, sizeof cmd, "AUTHENTICATE ");
	for (size_t i = 0; i < cl; i++) o += snprintf(cmd + o, sizeof cmd - (size_t)o, "%02x", (unsigned char)ck[i]);
	explicit_bzero(ck, cl); free(ck);
	rc = netman_tor_ctl_cmd(t, cmd, rep, sizeof rep); explicit_bzero(cmd, sizeof cmd);
	return rc == 250 ? 0 : -1;
}
int netman_tor_ctl_bootstrap(netman_tor_ctl *t, char *summary, size_t n)
{
	char rep[1024]; if (netman_tor_ctl_cmd(t, "GETINFO status/bootstrap-phase", rep, sizeof rep) != 250) return -1;
	char *p = strstr(rep, "PROGRESS="); if (!p) return -1;
	int pc = atoi(p + 9);
	if (summary && n) { summary[0] = 0; char *s = strstr(rep, "SUMMARY=\""); if (s) { s += 9; size_t k = strcspn(s, "\""); if (k >= n) k = n - 1; memcpy(summary, s, k); summary[k] = 0; } }
	return pc;
}
int netman_tor_ctl_circuits(netman_tor_ctl *t, int *built, char *fp, size_t n)
{
	char rep[8192]; *built = 0; if (n) fp[0] = 0;
	if (netman_tor_ctl_cmd(t, "GETINFO circuit-status", rep, sizeof rep) != 250) return -1;
	for (char *l = strtok(rep, "\n"); l; l = strtok(NULL, "\n")) {
		if (!strstr(l, " BUILT ") || !strstr(l, "PURPOSE=GENERAL")) continue;
		(*built)++;
		char *path = strstr(l, " BUILT "); path += 7;
		size_t k = strcspn(path, " "); char hops[512]; if (k >= sizeof hops) continue; memcpy(hops, path, k); hops[k] = 0;
		char *last = strrchr(hops, ','); last = last ? last + 1 : hops;
		if (*last == '$') { last++; size_t m = strcspn(last, "~="); if (m < n && m == 40) { memcpy(fp, last, m); fp[m] = 0; } }
	}
	return 0;
}
int netman_tor_ctl_exitip(netman_tor_ctl *t, const char *fp, char *ip, size_t n)
{
	char cmd[128], rep[2048]; if (strlen(fp) != 40 || strspn(fp, "0123456789abcdefABCDEF") != 40) return -1;
	snprintf(cmd, sizeof cmd, "GETINFO ns/id/%s", fp);
	if (netman_tor_ctl_cmd(t, cmd, rep, sizeof rep) != 250) return -1;
	for (char *l = strtok(rep, "\n"); l; l = strtok(NULL, "\n")) {
		char *r = strstr(l, "r ");
		if (r && (r == l || r[-1] == '-' || r[-1] == '+' || r[-1] == '\n')) {
			char nick[64], id[64], dg[64], d[32], tm[32], a[64];
			if (sscanf(r, "r %63s %63s %63s %31s %31s %63s", nick, id, dg, d, tm, a) == 6) { snprintf(ip, n, "%s", a); return 0; }
		}
	}
	return -1;
}
int netman_tor_ctl_newnym(netman_tor_ctl *t) { char r[256]; return netman_tor_ctl_cmd(t, "SIGNAL NEWNYM", r, sizeof r) == 250 ? 0 : -1; }
int netman_tor_ctl_reload(netman_tor_ctl *t) { char r[256]; return netman_tor_ctl_cmd(t, "SIGNAL RELOAD", r, sizeof r) == 250 ? 0 : -1; }

/* ---- persistence ----------------------------------------------------------------------------------------------------------- */
int netman_tor_load(netman_tor_cfg *c)
{
	size_t l; char *t = netman_vm_slurp(c->persist, &l, 64 << 10); if (!t) return 0;
	c->nbridges = 0; c->nhs = 0; c->exit_cc[0] = 0; c->strict = 0;
	for (char *sv = NULL, *ln = strtok_r(t, "\n", &sv); ln; ln = strtok_r(NULL, "\n", &sv)) {
		while (isspace((unsigned char)*ln)) ln++;
		if (!strncmp(ln, "bridge ", 7) && c->nbridges < 8) snprintf(c->bridges[c->nbridges++], sizeof c->bridges[0], "%s", ln + 7);
		else if (!strncmp(ln, "exit ", 5)) { char cc[8]; int st = 0; if (sscanf(ln + 5, "%7s %d", cc, &st) >= 1) { snprintf(c->exit_cc, sizeof c->exit_cc, "%s", cc); c->strict = st; } }
		else if (!strncmp(ln, "hs ", 3) && c->nhs < 4) { char nm[32], tg[64]; int p; if (sscanf(ln + 3, "%31s %d %63s", nm, &p, tg) == 3) { snprintf(c->hs[c->nhs].name, 32, "%s", nm); c->hs[c->nhs].port = p; snprintf(c->hs[c->nhs].target, 64, "%s", tg); c->nhs++; } }
	}
	free(t); return 0;
}
int netman_tor_save(const netman_tor_cfg *c)
{
	char b[8192]; sb s = { b, 0, sizeof b, 0 };
	sp(&s, "# written by `netman tor`; bridges, exit country and hidden services\n");
	for (int i = 0; i < c->nbridges; i++) sp(&s, "bridge %s\n", c->bridges[i]);
	if (c->exit_cc[0]) sp(&s, "exit %s %d\n", c->exit_cc, c->strict);
	for (int i = 0; i < c->nhs; i++) sp(&s, "hs %s %d %s\n", c->hs[i].name, c->hs[i].port, c->hs[i].target);
	char d[128]; snprintf(d, sizeof d, "%s", c->persist); char *sl = strrchr(d, '/'); if (sl) { *sl = 0; netman_vm_mkdirs(d, 0755); }
	return s.bad ? -1 : netman_vm_write(c->persist, b, s.n, 0600);
}

/* ---- process control --------------------------------------------------------------------------------------------------------- */
static int tor_ids(const netman_tor_cfg *c, unsigned *uid, unsigned *gid)
{
	struct passwd *p = getpwnam(c->tor_user); if (!p) return -1;
	*uid = p->pw_uid; *gid = p->pw_gid; return 0;
}
int netman_tor_running(const netman_tor_cfg *c)
{
	char pf[160]; snprintf(pf, sizeof pf, "%s/tor.pid", c->dir); return netman_vm_pid_alive(pf, "tor", NULL);
}
static void ctl_addr(const netman_tor_cfg *c, char *a, size_t n)
{
	if (c->control_port) snprintf(a, n, "127.0.0.1:%d", c->control_port); else snprintf(a, n, "unix:%s/control", c->dir);
}
static int connect_ctl(const netman_tor_cfg *c, netman_tor_ctl *t)
{
	char a[160]; ctl_addr(c, a, sizeof a);
	if (netman_tor_ctl_open(t, a)) return -1;
	if (netman_tor_ctl_auth(t)) { netman_tor_ctl_close(t); return -2; }
	return 0;
}
static int nft_load(const char *rules)
{
	char *av[] = { "nft", "-f", "-", NULL }; char out[512]; int st = 0;
	if (netman_vm_run(av, rules, out, sizeof out, 10000, &st) || !WIFEXITED(st) || WEXITSTATUS(st)) return -1;
	return 0;
}
static int nft_drop(void) { char *av[] = { "nft", "delete", "table", "inet", "netman_tor", NULL }; char o[256]; int st; netman_vm_run(av, NULL, o, sizeof o, 5000, &st); return 0; }

static int write_torrc(const netman_tor_cfg *c, unsigned uid, unsigned gid)
{
	char rc[8192], p[160]; if (netman_tor_torrc(c, rc, sizeof rc)) return -1;
	snprintf(p, sizeof p, "%s/data", c->dir); netman_vm_mkdirs(c->dir, 0700); netman_vm_mkdirs(p, 0700); if (chown(c->dir, uid, gid) || chown(p, uid, gid)) return -1;
	for (int i = 0; i < c->nhs; i++) {
		snprintf(p, sizeof p, "%s/hs", c->dir); netman_vm_mkdirs(p, 0700); if (chown(p, uid, gid)) return -1;
		snprintf(p, sizeof p, "%s/hs/%s", c->dir, c->hs[i].name); netman_vm_mkdirs(p, 0700); if (chown(p, uid, gid)) return -1;
	}
	snprintf(p, sizeof p, "%s/torrc", c->dir);
	return netman_vm_write(p, rc, strlen(rc), 0644);
}

int netman_tor_up(netman_tor_cfg *c)
{
	char err[160], bin[200], p[200]; unsigned uid, gid; int transparent = !strcmp(c->mode, "transparent");
	netman_tor_load(c);
	if (netman_tor_validate(c, err, sizeof err)) return fail(c, "%s", err);
	if (netman_tor_running(c)) return fail(c, "tor is already running (netman tor down first)");
	if (!netman_vm_which("tor", bin, sizeof bin)) return fail(c, "tor is not installed (pacman -S tor, apt install tor, ...). Nothing was changed.");
	if (tor_ids(c, &uid, &gid)) return fail(c, "no user '%s' (create it, or set tor.user). Nothing was changed.", c->tor_user);
	if (c->nbridges) {
		int ob = 0, sn = 0; char b2[200];
		for (int i = 0; i < c->nbridges; i++) { if (!strncmp(c->bridges[i], "obfs4 ", 6)) ob = 1; if (!strncmp(c->bridges[i], "snowflake ", 10)) sn = 1; }
		if (ob && !netman_vm_which(c->obfs4_bin, b2, sizeof b2)) return fail(c, "an obfs4 bridge is set but %s is not installed. Nothing was changed.", c->obfs4_bin);
		if (sn && !netman_vm_which(c->snowflake_bin, b2, sizeof b2)) return fail(c, "a snowflake bridge is set but %s is not installed. Nothing was changed.", c->snowflake_bin);
	}
	if (write_torrc(c, uid, gid)) return fail(c, "cannot write %s/torrc (needs root)", c->dir);
	if (transparent) {                                         /* FAIL CLOSED: the rules first, tor second */
		char rules[8192]; if (netman_tor_nft(c, uid, rules, sizeof rules)) return fail(c, "ruleset too large");
		if (!netman_vm_which("nft", p, sizeof p)) return fail(c, "nft is not installed: transparent mode needs it (use mode = socks for per-app). Nothing was changed.");
		if (nft_load(rules)) return fail(c, "loading the nftables rules failed; tor was NOT started");
		SAY(c, "firewall: table inet netman_tor loaded - everything but Tor is now blocked until `netman tor down`");
	}
	snprintf(p, sizeof p, "%s/torrc", c->dir);
	pid_t pid = fork();
	if (pid < 0) return fail(c, "fork: %s", strerror(errno));
	if (pid == 0) {
		setsid(); int dn = open("/dev/null", O_RDWR); if (dn >= 0) { dup2(dn, 0); dup2(dn, 1); dup2(dn, 2); }
		execl(bin, "tor", "-f", p, "--runasdaemon", "1", (char *)NULL); _exit(127);
	}
	int st; waitpid(pid, &st, 0);                            /* the daemon forks away; a failing config exits here */
	if (!WIFEXITED(st) || WEXITSTATUS(st)) { fail(c, "tor did not start (see %s/tor.log)%s", c->dir, transparent ? "; the firewall stays up: nothing leaks. `netman tor down` removes it" : ""); return 1; }
	SAY(c, "tor started; waiting for it to bootstrap");
	int pc = -1; netman_tor_ctl t; char sum[96] = "";
	for (int i = 0; i < 120; i++) {
		if (connect_ctl(c, &t) == 0) { pc = netman_tor_ctl_bootstrap(&t, sum, sizeof sum); netman_tor_ctl_close(&t); if (pc >= 100) break; }
		struct timespec ts = { 1, 0 }; nanosleep(&ts, NULL);
	}
	if (pc < 100) { fail(c, "tor is at %d%% (%s) after 120s: still starting, or blocked. The firewall stays up (nothing leaks). Try `netman tor bridge add ...`, or `netman tor down`", pc < 0 ? 0 : pc, sum); return 1; }
	SAY(c, "tor: up, bootstrapped 100%%. %s", transparent ? "All TCP and DNS of the routed users goes through Tor; everything else is dropped." : "SOCKS5 only; apps that ignore the setting are NOT protected.");
	return 0;
}
int netman_tor_down(netman_tor_cfg *c)
{
	char pf[160]; int pid = 0;
	snprintf(pf, sizeof pf, "%s/tor.pid", c->dir);
	if (netman_vm_pid_alive(pf, "tor", &pid) && pid > 1) {   /* tor first, rules after: no moment where the machine talks around Tor */
		kill(pid, SIGTERM);
		for (int i = 0; i < 100 && netman_vm_pid_alive(pf, "tor", NULL); i++) { struct timespec ts = { 0, 100000000 }; nanosleep(&ts, NULL); }
		if (netman_vm_pid_alive(pf, "tor", NULL)) kill(pid, SIGKILL);
	}
	nft_drop();
	SAY(c, "tor: down, firewall rules removed");
	return 0;
}
int netman_tor_status(netman_tor_cfg *c)
{
	netman_tor_load(c);
	int run = netman_tor_running(c);
	SAY(c, "tor      %s (%s mode)", run ? "running" : "not running", c->mode);
	SAY(c, "socks      127.0.0.1:%d   (per-app: curl --socks5-hostname 127.0.0.1:%d URL, or ALL_PROXY=socks5h://127.0.0.1:%d)", c->socks_port, c->socks_port, c->socks_port);
	if (!strcmp(c->mode, "transparent")) SAY(c, "transparent TransPort %d, DNSPort %d, routed uids: %s, forwarded from: %s", c->trans_port, c->dns_port, c->route_uids[0] ? c->route_uids : "all but tor", c->route_ifaces[0] ? c->route_ifaces : "none");
	SAY(c, "exit       %s%s", c->exit_cc[0] ? c->exit_cc : "any", c->exit_cc[0] && c->strict ? " (strict)" : "");
	SAY(c, "bridges    %d", c->nbridges);
	if (!run) return 0;
	netman_tor_ctl t; int rc = connect_ctl(c, &t);
	if (rc) { SAY(c, "control    unreachable%s", rc == -2 ? " (cookie authentication failed)" : ""); return 0; }
	char sum[96], fp[48], ip[64]; int pc = netman_tor_ctl_bootstrap(&t, sum, sizeof sum), built = 0;
	SAY(c, "bootstrap  %d%% %s", pc, sum);
	if (netman_tor_ctl_circuits(&t, &built, fp, sizeof fp) == 0) {
		SAY(c, "circuits   %d built", built);
		if (fp[0] && netman_tor_ctl_exitip(&t, fp, ip, sizeof ip) == 0) SAY(c, "exit ip    %s (as seen by Tor's directory; the last circuit's exit)", ip);
	}
	for (int i = 0; i < c->nhs; i++) {
		char p[200], *h; size_t l; snprintf(p, sizeof p, "%s/hs/%s/hostname", c->dir, c->hs[i].name);
		h = netman_vm_slurp(p, &l, 256);
		if (h) { while (l && isspace((unsigned char)h[l - 1])) h[--l] = 0; SAY(c, "hidden svc %s: %s:%d -> %s", c->hs[i].name, h, c->hs[i].port, c->hs[i].target); free(h); }
		else SAY(c, "hidden svc %s: (hostname not created yet)", c->hs[i].name);
	}
	netman_tor_ctl_close(&t);
	return 0;
}

static int apply_change(netman_tor_cfg *c)      /* after bridge/exit/hs edits: validate, save, and reload a running tor */
{
	char err[160]; unsigned uid, gid;
	if (netman_tor_validate(c, err, sizeof err)) return fail(c, "%s", err);
	if (netman_tor_save(c)) return fail(c, "cannot write %s (needs root)", c->persist);
	if (!netman_tor_running(c)) { SAY(c, "saved; it applies at the next `netman tor up`"); return 0; }
	if (tor_ids(c, &uid, &gid) || write_torrc(c, uid, gid)) return fail(c, "saved, but rewriting the torrc failed");
	netman_tor_ctl t; if (connect_ctl(c, &t) || netman_tor_ctl_reload(&t)) { if (t.fd >= 0) netman_tor_ctl_close(&t); return fail(c, "saved, but tor did not accept the reload (netman tor down; netman tor up)"); }
	netman_tor_ctl_close(&t); SAY(c, "saved and applied to the running tor"); return 0;
}
int netman_tor_main(netman_tor_cfg *c, int argc, char **argv)
{
	if (!c->out) c->out = stdout;
	if (!c->err) c->err = stderr;
	const char *cmd = argc > 0 ? argv[0] : "status";
	if (!strcmp(cmd, "up")) return netman_tor_up(c);
	if (!strcmp(cmd, "down")) return netman_tor_down(c);
	if (!strcmp(cmd, "status")) return netman_tor_status(c);
	netman_tor_load(c);
	if (!strcmp(cmd, "newnym")) {
		netman_tor_ctl t; if (!netman_tor_running(c)) return fail(c, "tor is not running");
		if (connect_ctl(c, &t) || netman_tor_ctl_newnym(&t)) return fail(c, "NEWNYM failed (control port unreachable or authentication refused)");
		netman_tor_ctl_close(&t); SAY(c, "new identity requested: new circuits for new connections (existing ones stay)"); return 0;
	}
	if (!strcmp(cmd, "bridge")) {
		if (argc >= 2 && !strcmp(argv[1], "clear")) { c->nbridges = 0; return apply_change(c); }
		if (argc >= 3 && !strcmp(argv[1], "add")) {
			char line[256] = ""; for (int i = 2; i < argc; i++) { if (strlen(line) + strlen(argv[i]) + 2 >= sizeof line) return fail(c, "bridge line too long"); snprintf(line + strlen(line), sizeof line - strlen(line), "%s%s", i > 2 ? " " : "", argv[i]); }
			if (c->nbridges >= 8) return fail(c, "at most 8 bridges (bridge clear)");
			snprintf(c->bridges[c->nbridges++], sizeof c->bridges[0], "%s", line); return apply_change(c);
		}
		return fail(c, "usage: netman tor bridge add 'obfs4 ADDR:PORT FPR cert=... iat-mode=0' | bridge clear");
	}
	if (!strcmp(cmd, "exit")) {
		if (argc >= 2 && !strcmp(argv[1], "off")) { c->exit_cc[0] = 0; c->strict = 0; return apply_change(c); }
		if (argc >= 2) { snprintf(c->exit_cc, sizeof c->exit_cc, "%s", argv[1]); c->strict = 1; return apply_change(c); }
		return fail(c, "usage: netman tor exit CC|off   (e.g. de; it is strict: if no such exit works, nothing connects)");
	}
	if (!strcmp(cmd, "hs")) {
		if (argc >= 2 && !strcmp(argv[1], "list")) { for (int i = 0; i < c->nhs; i++) SAY(c, "%s  %d -> %s", c->hs[i].name, c->hs[i].port, c->hs[i].target); return 0; }
		if (argc >= 5 && !strcmp(argv[1], "add")) {
			if (c->nhs >= 4) return fail(c, "at most 4 hidden services");
			snprintf(c->hs[c->nhs].name, 32, "%s", argv[2]); c->hs[c->nhs].port = atoi(argv[3]); snprintf(c->hs[c->nhs].target, 64, "%s", argv[4]); c->nhs++;
			int rc = apply_change(c); if (rc) return rc;
			if (netman_tor_running(c)) {
				for (int i = 0; i < 30; i++) {
					char p[200], *h; size_t l; snprintf(p, sizeof p, "%s/hs/%s/hostname", c->dir, argv[2]);
					if ((h = netman_vm_slurp(p, &l, 256))) { while (l && isspace((unsigned char)h[l - 1])) h[--l] = 0; SAY(c, "hidden service %s: %s", argv[2], h); free(h); return 0; }
					struct timespec ts = { 0, 500000000 }; nanosleep(&ts, NULL);
				}
				SAY(c, "tor has not written the hostname yet: see `netman tor status`");
			}
			return 0;
		}
		if (argc >= 3 && !strcmp(argv[1], "del")) {
			for (int i = 0; i < c->nhs; i++) if (!strcmp(c->hs[i].name, argv[2])) { c->hs[i] = c->hs[--c->nhs]; return apply_change(c); }
			return fail(c, "no hidden service %s", argv[2]);
		}
		return fail(c, "usage: netman tor hs add NAME PORT HOST:PORT | hs list | hs del NAME");
	}
	return fail(c, "unknown command %s (up, down, status, newnym, bridge add|clear, exit CC|off, hs add|list|del)", cmd);
}
